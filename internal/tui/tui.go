// Package tui는 의존성 없는 터미널 화면의 기반이다. worktree 화면과 생성 팝업이 함께 쓴다.
//
// 여기에는 화면 논리가 없다. raw 모드로 들어가고 나오는 일, 바이트를 키로 바꾸는 일, 줄 목록을
// 화면에 그리는 일, 그리고 ANSI 꾸밈 몇 가지뿐이다. 화면마다 다른 것(무엇을 어디에 그리는가)은
// 각 화면 패키지가 순수 함수로 두고 시험한다.
//
// 바깥 라이브러리를 쓰지 않는 이유가 있다. 이 플러그인은 표준 라이브러리만으로 세 플랫폼에
// 교차 컴파일되며, 화면 하나를 위해 그 약속을 깨기에는 필요한 것이 너무 적다. raw 모드는 플랫폼마다
// 다르지만 표준 라이브러리로 닿는다. 유닉스는 syscall.Termios 와 ioctl, 윈도우는 kernel32 의
// 콘솔 모드다. 플랫폼별 코드는 raw_*.go 에 있고, 나머지는 어디서나 같다.
//
// 되돌리기가 가장 중요하다. raw 모드로 들어갔다가 되돌리지 못하면 사용자의 셸이 망가진다.
// Terminal 은 오류 반환, 패닉, 신호 어느 길로 끝나도 원래대로 되돌린다. Run 을 쓰면 그 셋을 한 번에 얻는다.
// 다만 패닉은 그 고루틴의 지연 함수만 돌리고 프로세스를 끝내므로, 다른 고루틴은 Go 로 띄워야 같은 약속을 받는다.
